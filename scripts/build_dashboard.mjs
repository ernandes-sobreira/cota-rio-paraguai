import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {STATIONS,stationCard,timeBR,escapeHTML} from '../dashboard-core.js';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const overview=JSON.parse(read('data/overview.json')),latest=JSON.parse(read('data/latest.json'));
const json=v=>JSON.stringify(v).replace(/</g,'\\u003c');
const replacements={OVERVIEW:json(overview),LATEST:json(latest),VERIFIED:escapeHTML(timeBR(latest.last_success_at)),STATIONS:STATIONS.map((name,i)=>stationCard(name,overview.stations[name],latest.stations.find(s=>s.station===name),i,'history')).join('\n')};
const html=read('dashboard.template.html').replace(/\{\{(\w+)\}\}/g,(_,key)=>replacements[key]);
fs.writeFileSync(path.join(root,'index.html'),html);
const core=read('dashboard-core.js').replace(/^export /gm,'');
fs.writeFileSync(path.join(root,'dashboard.js'),`/* Generated by scripts/build_dashboard.mjs; edit dashboard-core.js and dashboard-client.js. */\n(function(){'use strict';\n${core}\n${read('dashboard-client.js')}\n})();\n`);
console.log('Painel estático e JavaScript gerados.');
